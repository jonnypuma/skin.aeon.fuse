"""0.56.44: the custom Home rows get plain-text <content target>s.

Kodi 22 evaluates a list's target attribute in CDirectoryProvider::StartDirectoryJob, which also runs on a JobWorker
(OnJobComplete, after a playback start/stop or library update invalidated the list while its job was running) while
holding the list's lock. Any info label in it (even Skin.String: the info providers' CVideoGUIInfo::GetLabel takes the
GUI lock on this build) then waits for the GUI lock that the main thread holds while it waits for the list's lock in
UpdateURL: the box froze (gdb 2026-11-18, leaving music Now playing; the Pictures freezes earlier the same day).

Each row list now has four <content>s (Kodi's multi provider routes click / info / context menu to the content that
gave the item), one per window, with a fixed target; the old target choice picks which content gets the row's path,
the others read the always-empty playlist. Paths are evaluated on the main thread (UpdateURL), so they may read infos.
"""
import io
import os
import re

SK = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '1080i')
F = os.path.join(SK, 'Includes_CustomRows.xml')
NONE = 'special://skin/shortcuts/customrows-none.xsp'
MUSIC = ('String.StartsWith(Skin.String(CustomRow.{n}.Path),musicdb://) | '
         'String.StartsWith(Skin.String(CustomRow.{n}.Path),library://music/) | '
         'String.StartsWith(Skin.String(CustomRow.{n}.Path),plugin://plugin.audio.) | '
         'String.StartsWith(Skin.String(CustomRow.{n}.Path),special://musicplaylists/) | '
         'String.Contains(Skin.String(CustomRow.{n}.Path),/playlists/music/)')
PROG = ('String.StartsWith(Skin.String(CustomRow.{n}.Path),plugin://plugin.program.) | '
        'String.StartsWith(Skin.String(CustomRow.{n}.Path),plugin://script.)')
KINDS = (('V', 'videos'), ('M', 'music'), ('P', 'programs'), ('I', 'pictures'))


def block(n):
    t = 'Skin.String(CustomRow.%d.Target)' % n
    m = '[%s] | [String.IsEmpty(%s) + [%s]]' % (
        ' | '.join('String.IsEqual(%s,%s)' % (t, w) for w in ('music', 'musiclibrary', '10502')), t, MUSIC.format(n=n))
    p = '[%s] | [String.IsEmpty(%s) + [%s]]' % (
        ' | '.join('String.IsEqual(%s,%s)' % (t, w) for w in ('programs', '10001')), t, PROG.format(n=n))
    i = ' | '.join('String.IsEqual(%s,%s)' % (t, w) for w in ('pictures', '10002'))
    exps = {'M': m, 'P': p, 'I': i, 'V': '![%s] + ![%s] + ![%s]' % (m, p, i)}
    out = []
    for k, _ in KINDS:
        out.append('\t<expression name="CustomRow_Kind%s%d">%s</expression>' % (k, n, exps[k]))
    for k, _ in KINDS:
        out.append('\t<variable name="CustomRow_Path%s%d">\n'
                   '\t\t<value condition="$EXP[CustomRow_Kind%s%d]">$VAR[CustomRow_Path%d]</value>\n'
                   '\t\t<value>%s</value>\n'
                   '\t</variable>' % (k, n, k, n, n, NONE))
    return '\n'.join(out)


def main():
    t = io.open(F, encoding='utf-8').read()
    if 'CustomRow_KindV1' in t:
        print('already done')
        return
    # the three target variables -> kind expressions + per-window path variables
    start = t.index('\t<variable name="CustomRow_Target1">')
    end = t.index('</variable>', t.index('<variable name="CustomRow_Target3">')) + len('</variable>')
    note = ('\t<!-- folder window of row n: what the picker stored, else a guess from the path. Kodi 22 reads a list\'s\n'
            '\t     target off the main thread (CDirectoryProvider::StartDirectoryJob) while holding the list\'s lock, so\n'
            '\t     an info label there can deadlock with the GUI lock (box froze 2026-11-18): the targets are plain text,\n'
            '\t     one <content> per window, and these choose which content gets the row\'s path (0.56.44). -->\n')
    t = t[:start] + '\n'.join(block(n) for n in (1, 2, 3)) + t[end:]
    t = t.replace('\t<!-- folder target of row n: what the picker stored, else a guess from the path -->\n', note)
    old = ('\t\t\t<content target="$VAR[CustomRow_Target$PARAM[row]]" limit="40" browse="never">'
           '$VAR[CustomRow_Path$PARAM[row]]</content>')
    new = '\n'.join('\t\t\t<content target="%s" limit="40" browse="never">$VAR[CustomRow_Path%s$PARAM[row]]</content>'
                    % (w, k) for k, w in KINDS)
    assert old in t
    t = t.replace(old, new)
    t = t.replace('\tGENERATED by tools/customrows/make_customrows.py - edit the generator, not this file.\n',
                  '\tFirst written by tools/customrows/make_customrows.py (gone); edited by hand / _src generators since.\n')
    t = t.replace('\tThe row lists have NO onclick: Kodi\'s list provider opens folders in the <content target> window and plays\n',
                  '\tThe row lists have NO onclick: Kodi\'s list provider opens folders in the <content target> window (one\n'
                  '\tplain-text target per <content>, see CustomRow_Kind*) and plays\n')
    assert '$VAR[CustomRow_Target' not in t
    io.open(F, 'w', encoding='utf-8', newline='\n').write(t)
    print('custom rows: 4 contents per row, plain targets')


if __name__ == '__main__':
    main()

# -*- coding: utf-8 -*-
"""0.56.42 the library strip's Music player opens a Now playing panel over the library (Aeon 2 ideas board, canvas
9dbV5SVnX2JrVdt9whh4qP, mockups/aeon2-ideas/project/PlayerOpen.dc.html). The user: "Build the Now playing overlay from
the library strip: YES!!!!" (and before: "what happened to the now playing opening an overlay from the settings strip ??").

Custom_1177_StripPlayer.xml (window 11177), every theme: the library dimmed, the strip's icon column with Music player
lit, and a 960 px panel beside it: the artist's backdrop at 28 %, the artist logo, the song, the artist, track and album,
year and label, the cover, the controls (previous, play / pause, next, the artist in the music library, full Now playing),
the song's progress with its times, and the next song. Back closes it and the library is where it was.
Custom_1178_StripPlayerClose.xml closes it when the music stops. The strip's button 300 (Includes_LibraryPanel.xml)
closes the strip and opens 1177 (it opened the full Now playing screen; that is the panel's last button now).
Run from the skin folder; rewrites both windows on every run."""
import io
import os
import xml.etree.ElementTree as ET

D = '1080i'
X = 81                    # the panel's left edge: right of the strip's 80 px icon column (and its 1 px line)
L = X + 80                # its content's left edge
BTN = [(101, 'prev', 'PlayerControl(Previous)'), (102, 'play', 'PlayerControl(Play)'), (103, 'next', 'PlayerControl(Next)'),
       (104, 'artist', 'RunScript(script.aeon.helper,npartist)'), (105, 'disc', 'ActivateWindow(visualisation)')]
FG = '$EXP[Aeon_FGlass]'


def button(n, cid, icon, action):
    x = L + n * 106
    out = ['\t\t\t<control type="button" id="%d">' % cid,
           '\t\t\t\t<left>%d</left><top>640</top><width>92</width><height>92</height><label></label>' % x,
           '\t\t\t\t<texturefocus /><texturenofocus />',
           '\t\t\t\t<onleft>%d</onleft><onright>%d</onright><onup>noop</onup><ondown>noop</ondown>' % (
               BTN[n - 1][0] if n else BTN[-1][0], BTN[n + 1][0] if n + 1 < len(BTN) else BTN[0][0])]
    if cid in (104, 105):
        out.append('\t\t\t\t<onclick>Dialog.Close(1177,true)</onclick>')
    out.append('\t\t\t\t<onclick>%s</onclick>' % action)
    out.append('\t\t\t</control>')
    # the focused control's white ground (a button's focus texture named by a variable is not drawn): Fused Glass's
    # round button, a square in Aeon / Aeon Glass
    for tex, cond in (('fg/btn90.png', FG), ('common/white.png', '!' + FG)):
        out.append('\t\t\t<control type="image"><left>%d</left><top>640</top><width>92</width><height>92</height>'
                   '<texture colordiffuse="ffededed">%s</texture><visible>Control.HasFocus(%d) + %s</visible></control>' % (x, tex, cid, cond))
    # the icon: white, dark on the focused (white) ground; play / pause follows the player
    for focused in (False, True):
        col = 'ff111114' if focused else 'ffffffff'
        vis = ('Control.HasFocus(%d)' if focused else '!Control.HasFocus(%d)') % cid
        if icon == 'play':
            for name, cond in (('pause', 'Player.Playing + !Player.Paused'), ('play', '![Player.Playing + !Player.Paused]')):
                out.append('\t\t\t<control type="image"><left>%d</left><top>670</top><width>32</width><height>32</height>'
                           '<aspectratio>keep</aspectratio><texture colordiffuse="%s">aeon/icons/%s.png</texture>'
                           '<visible>%s + %s</visible></control>' % (x + 30, col, name, vis, cond))
        else:
            out.append('\t\t\t<control type="image"><left>%d</left><top>670</top><width>32</width><height>32</height>'
                       '<aspectratio>keep</aspectratio><texture colordiffuse="%s">aeon/icons/%s.png</texture>'
                       '<visible>%s</visible></control>' % (x + 30, col, icon, vis))
    return '\n'.join(out)


def window():
    lab = '\t\t\t<control type="label"><left>%d</left><top>%%d</top><width>520</width><height>%%d</height><font>%%s</font>' \
          '<textcolor>%%s</textcolor><label>%%s</label></control>' % L
    o = ['<?xml version="1.0" encoding="UTF-8"?>',
         '<!-- GENERATED by _src/stripplayer_05642.py (0.56.42): the library strip\'s Music player, the left part of Now playing',
         '     over the library (Aeon 2 ideas board). Opened by the strip\'s button 300, closed by Back or by Custom_1178 when',
         '     the music stops. -->',
         '<window type="dialog" id="1177">',
         '\t<defaultcontrol always="true">102</defaultcontrol>',
         '\t<zorder>1</zorder>',
         '\t<controls>',
         '\t\t<!-- the library goes on behind, dimmed -->',
         '\t\t<control type="image"><width>1920</width><height>1080</height><texture colordiffuse="99000000">common/white.png</texture>'
         '<include>Anim_FadeVisible</include></control>',
         '\t\t<control type="group">',
         '\t\t\t<animation type="WindowOpen" condition="!Skin.HasSetting(aeon.reducemotion)"><effect type="slide" start="-300,0" end="0,0" time="320" tween="cubic" easing="out"/><effect type="fade" start="0" end="100" time="240"/></animation>',
         '\t\t\t<animation type="WindowOpen" condition="Skin.HasSetting(aeon.reducemotion)"><effect type="fade" start="0" end="100" time="200"/></animation>',
         '\t\t\t<animation type="WindowClose"><effect type="fade" start="100" end="0" time="200"/></animation>',
         '\t\t\t<!-- the panel: the artist\'s backdrop under a dark veil that deepens to the right, a soft shadow on its edge -->',
         '\t\t\t<control type="image"><left>%d</left><width>960</width><height>1080</height><texture colordiffuse="ff0c0c0e">common/white.png</texture></control>' % X,
         '\t\t\t<control type="image"><left>%d</left><width>960</width><height>1080</height><aspectratio>scale</aspectratio>'
         '<fadetime>300</fadetime><texture background="true" colordiffuse="47ffffff">$VAR[Aeon_NP_FanartBase]</texture></control>' % X,
         '\t\t\t<control type="image"><left>%d</left><width>960</width><height>1080</height><texture colordiffuse="590c0c0e">common/white.png</texture></control>' % X,
         '\t\t\t<control type="image"><left>%d</left><width>960</width><height>1080</height><texture colordiffuse="a00c0c0e">common/aeon_fade_left.png</texture></control>' % X,
         '\t\t\t<control type="image"><left>%d</left><width>60</width><height>1080</height><texture flipx="true" colordiffuse="8c000000">common/aeon_fade_left.png</texture></control>' % (X + 960),
         '\t\t\t<!-- the artist logo (the artist\'s name when there is none) -->',
         '\t\t\t<control type="image"><left>%d</left><top>112</top><width>380</width><height>120</height><aspectratio align="left" aligny="center">keep</aspectratio>'
         '<texture background="true">$VAR[Aeon_NP_ArtistLogo]</texture></control>' % L,
         '\t\t\t<control type="label"><left>%d</left><top>112</top><width>520</width><height>120</height><aligny>center</aligny><font>pl_display_40</font>'
         '<textcolor>ffffffff</textcolor><label>[UPPERCASE]$INFO[MusicPlayer.Artist][/UPPERCASE]</label>'
         '<visible>String.IsEmpty(Player.Art(artist.clearlogo)) + String.IsEmpty(Player.Art(clearlogo))</visible></control>' % L,
         '\t\t\t<!-- the song, the artist, track and album, year and label -->',
         lab % (268, 56, 'pl_display_40', 'ffffffff', '$INFO[MusicPlayer.Title]'),
         lab % (326, 34, 'pl_ui_24', 'ccffffff', '$INFO[MusicPlayer.Artist]'),
         lab % (388, 28, 'pl_cap_20', '99ffffff', '[UPPERCASE]$INFO[MusicPlayer.TrackNumber,$LOCALIZE[554] ,  ·  ]$LOCALIZE[558][/UPPERCASE]'),
         lab % (416, 34, 'pl_ui_24_bold', 'ffffffff', '[UPPERCASE]$INFO[MusicPlayer.Album][/UPPERCASE]'),
         lab % (462, 28, 'pl_cap_20', '99ffffff', '[UPPERCASE]$INFO[MusicPlayer.Year]$INFO[MusicPlayer.Property(Album_Label),  ·  ][/UPPERCASE]'),
         '\t\t\t<!-- the cover -->',
         '\t\t\t<control type="image"><left>%d</left><top>254</top><width>268</width><height>268</height><texture colordiffuse="66000000" border="20">fg/sh16.png</texture></control>' % (X + 626),
         '\t\t\t<control type="image"><left>%d</left><top>268</top><width>240</width><height>240</height><aspectratio>scale</aspectratio>'
         '<texture background="true">$VAR[Aeon_NP_Cover]</texture></control>' % (X + 640)]
    for n, (cid, icon, action) in enumerate(BTN):
        o.append(button(n, cid, icon, action))
    o += ['\t\t\t<!-- the song\'s progress and its times -->',
          '\t\t\t<control type="progress"><left>%d</left><top>800</top><width>800</width><height>4</height>'
          '<texturebg colordiffuse="2effffff">common/white.png</texturebg><midtexture colordiffuse="$VAR[Aeon_Accent]">common/white.png</midtexture>'
          '<info>Player.Progress</info></control>' % L,
          '\t\t\t<control type="label"><left>%d</left><top>818</top><width>400</width><height>34</height><font>pl_small_20</font>'
          '<textcolor>ccffffff</textcolor><label>$INFO[Player.Time]</label></control>' % L,
          '\t\t\t<control type="label"><left>%d</left><top>818</top><width>400</width><height>34</height><align>right</align><font>pl_small_20</font>'
          '<textcolor>ccffffff</textcolor><label>$INFO[Player.Duration]</label></control>' % (L + 400),
          '\t\t\t<!-- the next song -->',
          '\t\t\t<control type="label"><left>%d</left><top>924</top><width>800</width><height>34</height><font>pl_cap_20</font>'
          '<textcolor>8cffffff</textcolor><label>[UPPERCASE]$LOCALIZE[209]   [COLOR ffffffff][B]$INFO[MusicPlayer.offset(1).Title][/B][/COLOR]$INFO[MusicPlayer.offset(1).Duration,  ·  ][/UPPERCASE]</label>'
          '<visible>!String.IsEmpty(MusicPlayer.offset(1).Title)</visible></control>' % L,
          '\t\t\t<!-- the strip\'s icon column, Music player lit -->',
          '\t\t\t<control type="image"><width>80</width><height>1080</height><texture colordiffuse="ff141416">common/white.png</texture></control>',
          '\t\t\t<control type="image"><left>80</left><width>1</width><height>1080</height><texture colordiffuse="1affffff">common/white.png</texture></control>',
          '\t\t\t<control type="image"><top>972</top><width>80</width><height>108</height><texture colordiffuse="ffededed">common/white.png</texture></control>',
          '\t\t\t<control type="image"><left>19</left><top>1000</top><width>42</width><height>50</height><texture colordiffuse="ff111114">common/aeon_eq_anim.gif</texture>'
          '<visible>Player.Playing + !Player.Paused + !Skin.HasSetting(aeon.reducemotion)</visible></control>',
          '\t\t\t<control type="image"><left>19</left><top>1000</top><width>42</width><height>50</height><texture colordiffuse="ff111114">common/aeon_eq_still.png</texture>'
          '<visible>![Player.Playing + !Player.Paused + !Skin.HasSetting(aeon.reducemotion)]</visible></control>',
          '\t\t</control>',
          '\t</controls>',
          '</window>', '']
    p = os.path.join(D, 'Custom_1177_StripPlayer.xml')
    io.open(p, 'w', encoding='utf-8', newline='\n').write('\n'.join(o))
    ET.parse(p)
    c = ['<?xml version="1.0" encoding="UTF-8"?>',
         '<!-- GENERATED by _src/stripplayer_05642.py (0.56.42): closes the strip\'s Now playing panel (1177) when the music stops -->',
         '<window type="dialog" id="1178">',
         '\t<visible>Window.IsVisible(1177) + !Player.HasAudio</visible>',
         '\t<onload>Dialog.Close(1177,true)</onload>',
         '\t<onload>Dialog.Close(1178,true)</onload>',
         '\t<controls/>',
         '</window>', '']
    p = os.path.join(D, 'Custom_1178_StripPlayerClose.xml')
    io.open(p, 'w', encoding='utf-8', newline='\n').write('\n'.join(c))
    ET.parse(p)


def variables():
    """the strip's button 300 opens the panel"""
    p = os.path.join(D, 'Includes_LibraryPanel.xml')
    t = io.open(p, encoding='utf-8').read()
    # the strip's Music player button opens the panel (it opened the full Now playing screen)
    old = '\t\t\t\t<onclick>Dialog.Close(1160,true)</onclick>\n\t\t\t\t<onclick>ActivateWindow(visualisation)</onclick>\n'
    new = '\t\t\t\t<onclick>Dialog.Close(1160,true)</onclick>\n\t\t\t\t<onclick>ActivateWindow(1177)</onclick>\n'
    if old in t:
        t = t.replace(old, new)
    assert new in t
    io.open(p, 'w', encoding='utf-8', newline='\n').write(t)
    ET.parse(p)


if __name__ == '__main__':
    window()
    variables()
    print('ok')
